export function getPrescribedWorkout(
  arena: ArenaId,
  split: SplitId,
  gateRank: GateRankId
): ExerciseSpec[] {
  const arenaMap = WORKOUT_MATRIX[arena] ?? WORKOUT_MATRIX.cg_gym;
  const raw = split as string;
  const safeSplit: SplitId =
    raw === "push"
      ? "upper_a"
      : raw === "pull"
        ? "upper_b"
        : raw === "legs"
          ? "lower_a"
          : raw === "pool_steps"
            ? "cardio_pool"
            : split;
  const list = arenaMap[safeSplit] ?? arenaMap.upper_a;
  const isCardio = safeSplit === "cardio_pool";

  return list.map((ex) => {
    if (isCardio) return ex;
    const isLowTime = gateRank === "low_time_2x";
    const scaledSets = isLowTime ? 2 : 3;
    const scaledSwapSets = scaledSets;
    const isCompound = ex.id === "cg_bench" || ex.id === "cg_bb_rdl" || ex.id === "cg_bb_rdl_b" || ex.id === "cg_bench_vol";
    const scaledReps = ex.timeBased
      ? ex.reps
      : isLowTime
        ? "Fail (<=19)"
        : isCompound
          ? "10-15"
          : "12-15";
    const isSwapTimeBased = /\d+s\b|\bmin\b/i.test(ex.swap.reps);
    const scaledSwapReps = isSwapTimeBased
      ? ex.swap.reps
      : isLowTime
        ? "Fail (<=19)"
        : "12-15";

    return {
      ...ex,
      sets: scaledSets,
      reps: scaledReps,
      swap: {
        ...ex.swap,
        sets: scaledSwapSets,
        reps: scaledSwapReps,
      },
    };
  });
}

